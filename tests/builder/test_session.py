"""The Builder session: writes are ruled with rows, the read surface is fenced, the bus is gapless."""

from __future__ import annotations

import json

from kullback.agent.events import ToolExecutionEnd as ToolEnd
from kullback.ai.provider import TestModel
from kullback.builder import session as session_mod
from kullback.runner.records import RawPtr, ToolCall, Trace, Turn
from tests.builder.session_fixtures import reply
from tests.episode.invented import write_env

PTR = RawPtr(file_hash="f" * 64, sim_index=0, msg_index=0)

SMUDGED_BODY = (
    "row = self.db.widgets.get(widget_id)\n"
    "if row is None:\n"
    "    raise KeyError(widget_id)\n"
    'row.label = "smudged"\n'
    'return {"widget_id": widget_id, "label": "smudged"}'
)

TOOL_FILE = ("# Generated by the harness from the recorded calls. Edit the body in place.\n"
             "from typing import Any, Optional\n\n"
             "def rename_widget(self, widget_id, label):\n"
             "    row = self.db.widgets.get(widget_id)\n"
             "    if row is None:\n"
             "        raise KeyError(widget_id)\n"
             '    row.label = "smudged"\n'
             '    return {"widget_id": widget_id, "label": "smudged"}\n')


def _workdir(tmp_path):
    root = write_env(tmp_path / "work")
    traces = root / "traces"
    traces.mkdir(parents=True, exist_ok=True)
    turns = [
        Turn(idx=0, role="assistant", content="Hi! How can I help?", raw_ptr=PTR),
        Turn(idx=1, role="user", content="Give widget w1 the label striped.", raw_ptr=PTR),
        Turn(idx=2, role="assistant", content=None, tool_call_ids=["c1"], raw_ptr=PTR),
        Turn(idx=3, role="tool", content='{"widget_id": "w1"}', tool_call_ids=["c1"],
             raw_ptr=PTR),
        Turn(idx=4, role="assistant", content=None, tool_call_ids=["c2"], raw_ptr=PTR),
        Turn(idx=5, role="tool", content='{"widget_id": "w1"}', tool_call_ids=["c2"],
             raw_ptr=PTR),
        Turn(idx=6, role="assistant", content="Done.", raw_ptr=PTR),
        Turn(idx=7, role="user", content="Thanks, that is the right label.", raw_ptr=PTR),
    ]
    calls = [
        ToolCall(id="c1", name="describe_widget", args={"widget_id": "w1"},
                 result={"widget_id": "w1", "label": "plain"}, raw_ptr=PTR, trace_id="rec1"),
        ToolCall(id="c2", name="rename_widget", args={"widget_id": "w1", "label": "striped"},
                 result={"widget_id": "w1", "label": "striped"}, raw_ptr=PTR, trace_id="rec1"),
    ]
    trace = Trace(trace_id="rec1", raw_hash="r" * 64, ingest_version="1", source="test",
                  turns=turns, tool_calls=calls, raw_ptr=PTR)
    (traces / "rec1.json").write_text(json.dumps(trace.model_dump(mode="json", by_alias=True)),
                                      encoding="utf-8")
    return root


def _scripted_session(tmp_path):
    root = _workdir(tmp_path)
    model = TestModel([
        reply("Writing the body.",
              ("write", {"path": "tools/rename_widget.py", "content": TOOL_FILE})),
        reply("Trying a read-only path.", ("write", {"path": "schema.json", "content": "{}"})),
        reply("Trying the shell.", ("bash", {"command": "cat ../traces/rec1.json"})),
        reply("Reading the calls.", ("read", {"path": "calls/rename_widget.jsonl"})),
        reply("Done."),
    ])
    ends = []
    result = session_mod.build(
        root, model,
        subscribers=[lambda event: ends.append(event) if isinstance(event, ToolEnd) else None])
    return root, result, [event for event in ends if isinstance(event, ToolEnd)]


def test_a_tool_write_is_ruled_with_a_fidelity_ruling_carrying_rows(tmp_path):
    root, _, ends = _scripted_session(tmp_path)
    write = next(end for end in ends if end.tool_name == "write" and not end.is_error)
    rulings = write.result.details.get("rulings") or []
    assert rulings, "a write under tools/ draws rulings"
    fidelity = [ruling for ruling in rulings if "fidelity" in ruling["name"]]
    assert fidelity, f"a fidelity ruling is among {[r['name'] for r in rulings]}"
    assert fidelity[0]["rows"], "the fidelity ruling carries per-call rows"
    assert not fidelity[0]["accepted"]
    assert (root / "env" / "tools.py").read_text(encoding="utf-8").count("smudged") >= 1
    assert "smudged" in json.loads((root / "bodies.json").read_text(encoding="utf-8"))["rename_widget"]


def test_a_write_outside_the_four_directories_is_refused(tmp_path):
    _, _, ends = _scripted_session(tmp_path)
    refused = [end for end in ends if end.tool_name == "write" and end.is_error]
    assert len(refused) == 1
    assert "schema.json" in refused[0].result.content


def test_a_shell_step_above_the_root_is_refused(tmp_path):
    _, _, ends = _scripted_session(tmp_path)
    refused = [end for end in ends if end.tool_name == "bash"]
    assert len(refused) == 1 and refused[0].is_error


def test_a_read_of_the_exposed_calls_works(tmp_path):
    _, _, ends = _scripted_session(tmp_path)
    read = next(end for end in ends if end.tool_name == "read")
    assert not read.is_error
    assert "c2" in read.result.content


def test_the_session_ends_when_the_model_answers_without_a_tool_call(tmp_path):
    _, result, _ = _scripted_session(tmp_path)
    assert result["stopped"] == "the model answered with no tool call"
    assert not result["ceiling_reached"]


def test_the_bus_holds_the_events_in_gapless_order(tmp_path):
    root, result, _ = _scripted_session(tmp_path)
    lines = (root / "bus.jsonl").read_text(encoding="utf-8").splitlines()
    assert len(lines) == result["events"]
    seqs = [json.loads(line)["seq"] for line in lines]
    assert seqs == list(range(1, len(lines) + 1))
